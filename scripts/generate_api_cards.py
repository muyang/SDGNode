#!/usr/bin/env python3
"""管线 3 · API 数据源工厂（SDGNode P0）。

读取 sources/*.source.yaml，为每个 REST 统计/主题数据源生成**成对**卡片：

    cards/data/<namespace>.<product>.yaml    data 卡（statistical 语义 + geonexus:statistical 扩展）
    cards/skill/stats.fetch-<id>.yaml        伴生 fetch skill 卡（geomcp-skill 接口）

设计依据：《GeoNexus-SDG能力注册技术方案》§5 管线 3——REST API 源拆成
"数据卡（身份/契约/合规）+ fetch skill（执行入口）"两半注册。
生成卡是**可再生产物**：请勿手改生成文件，改 sources/*.source.yaml 后重跑本脚本。

用法：
    python scripts/generate_api_cards.py [--sources sources] [--dry-run]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]

HEADER = (
    "# GENERATED by scripts/generate_api_cards.py — do not edit by hand.\n"
    "# Source manifest: sources/{src}\n"
)


def dump_yaml(doc: dict[str, Any], path: Path, src_name: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=110)
    path.write_text(HEADER.format(src=src_name) + body, encoding="utf-8")


def build_cards(m: dict[str, Any], src_name: str) -> tuple[str, dict, str, dict]:
    ns, product = m["namespace"], m["product"]
    provider = m["provider"]
    api, cov, sdg = m["api"], m["coverage"], m.get("sdg", {})
    compliance = dict(m.get("compliance", {"sovereignty": "intl", "sensitivity": "public"}))
    sk = m["skill"]

    data_id = f"sdg.data.{ns}.{product}"
    skill_id = f"sdg.skill.stats.{sk['id']}"
    goals = list(sdg.get("goals", []))

    data_card: dict[str, Any] = {
        "geocard_version": "1.0",
        "id": data_id,
        "type": "data",
        "name": m["name"],
        "description": m["description"],
        "tags": ["statistics", "api-source", "generated", "non-spatial"] + [f"sdg:{g}" for g in goals],
        "capabilities": [{"name": "indicator-query", "description": "按指标/区域/时间维度查询序列"}],
        "access": {
            "protocol": "https",
            "endpoint": api["base_url"],
            "auth": api.get("auth", "none"),
            "format": api.get("response_format", "JSON"),
        },
        "provenance": {
            "provider": provider,
            "source": api.get("docs", api["base_url"]),
            "lineage": f"管线 3 工厂生成（sources/{src_name}）；statistical 合约字段由 GAAG 注册扫描复核",
        },
        "license": m["license"],
        "compliance": compliance,
        "trust": {"verified": False, "score": 0.8},
        "geonexus:sdg": {
            "goals": goals,
            "custodian": sdg.get("custodian", provider),
            "tier": sdg.get("tier", "unclassified"),
            "related_cards": [skill_id],
            "source_manifest": f"sources/{src_name}",
        },
        # 扩展：statistical 合约声明（GAAG scan_statistical 在注册时按实际快照复核）
        "geonexus:statistical": {
            "columns": list(cov["columns"]),
            "record_count": cov.get("record_count"),
            "spatial_key": cov.get("spatial_key"),
            "time_key": cov.get("time_key"),
            "update_interval": cov.get("update_interval"),
        },
    }

    skill_compliance = {
        "sovereignty": compliance.get("sovereignty", "intl"),
        "sensitivity": "public",
    }
    skill_card: dict[str, Any] = {
        "geocard_version": "1.0",
        "id": skill_id,
        "type": "skill",
        "name": sk["name"],
        "description": sk["description"],
        "tags": ["api-fetch", "generated", "stats"],
        "interface": {"type": "geomcp-skill", "version": "1.0"},
        "capabilities": ["indicator-query", "data-fetch"],
        "inputs": sk["inputs"],
        "outputs": sk["outputs"],
        "access": {"protocol": "geomcp", "endpoint": sk["node_endpoint"], "auth": "apikey"},
        "provenance": {
            "provider": "SDGNode",
            "source": f"配对数据卡 {data_id}",
            "lineage": "管线 3 工厂生成；handler 实现随 P1 交付（容器化技能）",
        },
        "license": "Apache-2.0",
        "compliance": skill_compliance,
        "geonexus:sdg": {"goals": goals, "related_cards": [data_id]},
    }
    return data_id, data_card, skill_id, skill_card


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources", default=str(ROOT / "sources"))
    ap.add_argument("--cards-dir", default=str(ROOT / "cards"))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    cards_dir = Path(args.cards_dir)
    manifests = sorted(Path(args.sources).glob("*.source.yaml"))
    if not manifests:
        print(f"no manifests under {args.sources}", file=sys.stderr)
        return 1

    n = 0
    for mf in manifests:
        m = yaml.safe_load(mf.read_text(encoding="utf-8"))
        data_id, data_card, skill_id, skill_card = build_cards(m, mf.name)
        data_path = cards_dir / "data" / f"{m['namespace']}.{m['product']}.yaml"
        skill_path = cards_dir / "skill" / f"stats.{m['skill']['id']}.yaml"
        if args.dry_run:
            print(f"[dry-run] {data_id} -> {data_path}\n[dry-run] {skill_id} -> {skill_path}")
        else:
            dump_yaml(data_card, data_path, mf.name)
            dump_yaml(skill_card, skill_path, mf.name)
            print(f"generated: {data_path.relative_to(ROOT)}  +  {skill_path.relative_to(ROOT)}")
        n += 2
    print(f"done: {n} cards from {len(manifests)} manifests")
    return 0


if __name__ == "__main__":
    sys.exit(main())
